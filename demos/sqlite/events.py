"""Immutable demo events and a standard-library JSON/SSE profile.

This consumer defines its own progress/finished vocabulary and DONE/ERROR
statuses. It does not import the optional Pydantic/Redis profile.
"""

import json
from dataclasses import asdict, dataclass
from typing import Any

from demos.sqlite.constants import TOTAL_STEPS, EventKind, JobStatus
from ui_stream.exceptions import InvalidEvent
from ui_stream.sse import encode_sse_heartbeat
from ui_stream.types import EncodingTarget


def json_bytes(value: Any) -> bytes:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), allow_nan=False).encode("utf-8")


@dataclass(frozen=True, slots=True)
class DemoEvent:
    kind: str
    step: int | None = None
    total: int = TOTAL_STEPS
    message: str = ""
    status: str | None = None
    cursor: int | None = None

    def as_dict(self, *, include_cursor=True) -> dict:
        value = asdict(self)
        if not include_cursor:
            value.pop("cursor")
        return value


class DemoCodec:
    """Validate synthetic progress and encode transport/archive views without I/O."""

    def business(self, data: Any) -> DemoEvent:
        if not isinstance(data, DemoEvent) or data.kind != EventKind.PROGRESS:
            raise InvalidEvent("Demo requires a progress event")
        if type(data.step) is not int or not 1 <= data.step <= TOTAL_STEPS or not isinstance(data.message, str):
            raise InvalidEvent("Invalid synthetic progress")
        return data

    def terminal(self, status: str) -> DemoEvent:
        if status not in (JobStatus.DONE, JobStatus.ERROR, JobStatus.INTERRUPTED):
            raise InvalidEvent("Invalid demo terminal status")
        return DemoEvent(kind=EventKind.FINISHED, status=status)

    def reset(self, reason: str) -> DemoEvent:
        """构造 Demo 自己的 reset 消息，保留 profile 的整数游标边界。"""

        if not isinstance(reason, str):
            raise InvalidEvent("Reset reason must be text")
        return DemoEvent(kind=EventKind.RESET, message=reason)

    def encode(self, event: DemoEvent, target: EncodingTarget) -> bytes:
        return json_bytes(event.as_dict(include_cursor=target == EncodingTarget.ARCHIVE))


def sse_frame(kind: EventKind, data: Any, *, cursor: int | None = None) -> bytes:
    # Event names and IDs are generated by this profile, never arbitrary header text.
    name = EventKind(kind)
    identifier = "" if cursor is None else f"id: {int(cursor)}\n"
    return f"event: {name}\n{identifier}data: ".encode() + json_bytes(data) + b"\n\n"


@dataclass(frozen=True, slots=True)
class DemoSSEMessage:
    """HTTP 层的 Demo 消息，保留自己的事件名、payload 与整数游标。"""

    kind: EventKind
    data: Any
    cursor: int | None = None


def encode_sse_message(message: DemoSSEMessage | None) -> bytes:
    """适配通用同步响应体；None 只是本连接的心跳，不影响生产者。"""

    if message is None:
        return encode_sse_heartbeat()
    return sse_frame(message.kind, message.data, cursor=message.cursor)
